export const getCitiesByProvince = (provinceCode: string): City[] => {
  return cities.filter((city) => city.provinceCode === provinceCode)
}

export const getDistrictsByCity = (cityCode: string): District[] => {
  return districts.filter((district) => district.cityCode === cityCode)
}

export const getProvinceByCode = (code: string): Province | undefined => {
  return provinces.find((p) => p.code === code)
}

export const getCityByCode = (code: string): City | undefined => {
  return cities.find((c) => c.code === code)
}

export const getDistrictByCode = (code: string): District | undefined => {
  return districts.find((d) => d.code === code)
}

export const getProvinceByName = (name: string): Province | undefined => {
  return provinces.find((p) => p.name === name)
}

export const getCityByName = (name: string, provinceCode?: string): City | undefined => {
  return cities.find((c) => c.name === name && (!provinceCode || c.provinceCode === provinceCode))
}

