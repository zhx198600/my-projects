export const getProvinceCoord = (provinceName: string): [number, number] | null => {
  const cleanedName = provinceName.replace(/(省|市|自治区|特别行政区)$/, '')

  for (const [name, coord] of Object.entries(provinceCoords)) {
    if (
      name.includes(cleanedName) ||
      cleanedName.includes(name.replace(/(省|市|自治区|特别行政区)$/, ''))
    ) {
      return coord
    }
  }

  return provinceCoords[provinceName] || null
}

export const getCityCoord = (cityName: string): [number, number] | null => {
  return cityCoords[cityName] || null
}

export const getDistrictCoord = (districtName: string): [number, number] | null => {
  return districtCoords[districtName] || null
}

export const getCoordByName = (
  name: string,
  level: 'province' | 'city' | 'district' = 'province'
): [number, number] | null => {
  if (level === 'province') {
    return getProvinceCoord(name)
  } else if (level === 'city') {
    return getCityCoord(name)
  } else {
    return getDistrictCoord(name)
  }
}
