export const districtCoords: Record<string, [number, number]> = {}

const generateDistrictCoords = () => {
  for (const district of districts) {
    const city = cities.find((c) => c.code === district.cityCode)
    if (city) {
      const cityCoord = cityCoords[city.name]
      if (cityCoord) {
        const angle = Math.random() * 2 * Math.PI
        const radius = 0.15 + Math.random() * 0.2
        districtCoords[district.name] = [
          cityCoord[0] + Math.cos(angle) * radius,
          cityCoord[1] + Math.sin(angle) * radius,
        ]
      }
    }
  }
}

