const API_BASE_URL = 'https://trae-api-cn.mchost.guru/api/ide/v1/text_to_image';

export function generateImageUrl(prompt, imageSize = 'square_hd') {
  const encodedPrompt = encodeURIComponent(prompt);
  return `${API_BASE_URL}?prompt=${encodedPrompt}&image_size=${imageSize}`;
}

